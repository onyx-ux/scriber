// that 404s is worse than no link, and this is the only way to be sure.
//
// GENERATED, from each wiki's own spell index. 570-odd names and slugs typed by
// hand would be 570 chances to misspell one; taken from the index, a slug is
// right by construction. Regenerate rather than edit — see the note in
// test/rules.test.js about what to re-check if the shape of those pages moves.
//
// WHAT IS NOT HERE, and why. Conditions, monsters, skills and classes are the
// terms a session recap says most, and NEITHER wiki has a page for any of them:
// /conditions, /grappled, /monster:goblin, /class:wizard and every variation
// tried are all 404 on both. Checked 2026-09-04, not assumed. So this links
