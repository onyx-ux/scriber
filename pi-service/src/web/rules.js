export const EDITIONS = {
  // HTTPS, deliberately, for both.
  //
  // dnd2024.wikidot.com answers a 301 from https to http — it has no working
  // certificate — so a reader following one of these ends up on plain HTTP
  // whatever we write. Writing https is us asking for the secure one and the
  // site refusing, rather than us choosing the insecure one; and the day they
  // fix it, these links are already right.
  '2014': { label: '2014 rules', base: 'https://dnd5e.wikidot.com/', bit: 1 },
  '2024': { label: '2024 rules', base: 'https://dnd2024.wikidot.com/', bit: 2 },
};

export const DEFAULT_EDITION = '2024';

export const isEdition = (e) => Object.hasOwn(EDITIONS, String(e ?? ''));

// The spells a given edition can actually answer for, as { name, url }.
//
// Built per edition rather than filtered per lookup, because the dashboard asks
// once and matches every name in a write-up against the answer.
export function rulesFor(edition = DEFAULT_EDITION) {
  const ed = EDITIONS[isEdition(edition) ? edition : DEFAULT_EDITION];
  return SPELLS
    .filter(([, , on]) => on & ed.bit)
    .map(([name, slug]) => ({ name, url: `${ed.base}spell:${slug}` }));
}

