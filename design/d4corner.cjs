// The d4 in the corner of "Four things", from the same kind of small 3D model
// as the tray: a tetrahedron sitting on its base, turned so the face that
// carries the 4 looks left, towards the heading.
const fs = require('fs');
const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const add = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
const mul = (a, k) => [a[0] * k, a[1] * k, a[2] * k];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const unit = (a) => mul(a, 1 / Math.hypot(...a));
const mean = (ps) => mul(ps.reduce(add, [0, 0, 0]), 1 / ps.length);

const ELEV = 30 * Math.PI / 180, se = Math.sin(ELEV), ce = Math.cos(ELEV);
const P = ([x, y, z]) => [x, -(y * se + z * ce)];           // camera in front, looking down a little
const TOCAM = [0, -ce, se];

const A = 74, R = A / Math.sqrt(3), Hh = A * Math.sqrt(2 / 3);
const TURN = Number(process.argv[2] || 222);                 // which way the 4 face looks, in plan
const base = [TURN - 60, TURN + 60, TURN + 180].map((d) => { const t = d * Math.PI / 180; return [R * Math.cos(t), R * Math.sin(t), 0]; });
const apex = [0, 0, Hh], centre = mean([...base, apex]);
const faces = [[base[0], base[1], '4'], [base[1], base[2], '1'], [base[2], base[0], '3']].map(([p, q, label]) => {
  const c = mean([p, q, apex]);
  let n = unit(cross(sub(q, p), sub(apex, p)));
  if (dot(n, sub(c, centre)) < 0) n = mul(n, -1);
  return { p, q, c, n, label, facing: dot(n, TOCAM) };
}).filter((f) => f.facing > 0.02);

const f1 = (n) => (Math.round(n * 10) / 10).toString();
const pt = (p) => P(p).map(f1).join(' ');
let svg = '';
for (const f of faces) {
  svg += `<path d="M${pt(f.p)}L${pt(f.q)}L${pt(apex)}Z"/>`;
  if (f.facing < 0.25) continue;
  const up = unit(sub(apex, mean([f.p, f.q]))), right = cross(up, f.n);
  const a = P(right), d = P(mul(up, -1)), e = P(f.c);
  // The projection of a direction, not a point: P is linear, so this is right.
  const big = f.label === '4', s = (A / (2 * Math.sqrt(3))) * (big ? 1.25 : 0.95);
  svg += `<text transform="matrix(${[a[0], a[1], d[0], d[1], e[0], e[1]].map((v) => Math.round(v * 1000) / 1000).join(' ')})" y="${f1(s * 0.5)}" font-size="${f1(s)}"${big ? ' font-weight="500"' : ''}>${f.label}</text>`;
}
// Something for it to sit on: the shadow it throws on the table, hatched the
// way a pen would. Light from the upper left, so it falls away from the heading.
const hull = (ps) => { // convex hull of 2D points, counter-clockwise
  const s = [...ps].sort((a, b) => a[0] - b[0] || a[1] - b[1]), cr = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const half = (list) => { const h = []; for (const p of list) { while (h.length > 1 && cr(h[h.length - 2], h[h.length - 1], p) <= 0) h.pop(); h.push(p); } h.pop(); return h; };
  return [...half(s), ...half(s.reverse())];
};
const inside = (h, p) => h.every((a, i) => { const b = h[(i + 1) % h.length]; return (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0]) >= 0; });
const LIGHT = [1.15, -0.3];                                   // where the apex's shadow lands, per unit of height
const tip = [apex[2] * LIGHT[0], apex[2] * LIGHT[1]];
const shade = hull([...base.map((b) => [b[0], b[1]]), tip]), outline = hull([...base, apex].map(P));
const hd = [Math.cos(0.5), Math.sin(0.5)], hn = [-hd[1], hd[0]];
const shadowPts = [];
let hatch = '';
for (let o = -140; o <= 140; o += 6.5) {
  let run = null;
  for (let t = -160; t <= 160; t += 0.5) {
    const g = [hn[0] * o + hd[0] * t, hn[1] * o + hd[1] * t], scr = P([g[0], g[1], 0]);
    const on = inside(shade, g) && !inside(outline, scr);
    if (on) { if (!run) run = [scr, scr]; else run[1] = scr; shadowPts.push(scr); }
    if (!on && run) { hatch += `M${run[0].map(f1).join(' ')}L${run[1].map(f1).join(' ')}`; run = null; }
  }
}
svg += `<path d="${hatch}" stroke-width="1"/>`;

const pts = [...base, apex].map(P).concat(shadowPts), xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
const pad = 4, x0 = Math.min(...xs) - pad, y0 = Math.min(...ys) - pad, w = Math.max(...xs) - x0 + pad, h = Math.max(...ys) - y0 + pad;
const out = `<svg class="inkmark die" viewBox="${f1(x0)} ${f1(y0)} ${f1(w)} ${f1(h)}" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linejoin="round" stroke-linecap="round" aria-hidden="true">
      <!-- A d4 sitting on its base, its 4 turned towards the heading.
           Generated by a small 3D model (design/d4corner.cjs). -->
      <g font-family="Spline Sans Mono, monospace" text-anchor="middle" fill="currentColor" stroke="none">${svg.match(/<text[^]*?<\/text>/g).join('')}</g>
      ${svg.replace(/<text[^]*?<\/text>/g, '')}
    </svg>`;

const f = require('path').join(__dirname, '..', 'dashboard', 'html', 'quill-landing.html');
let s = fs.readFileSync(f, 'utf8');
const i = s.indexOf('<svg class="inkmark die"'), j = s.indexOf('</svg>', i) + 6;
if (i < 0) throw new Error('no corner die');
s = s.slice(0, i) + out + s.slice(j);
fs.writeFileSync(f, s);
console.log('ok', faces.map((x) => x.label + ':' + x.facing.toFixed(2)).join(' '), 'viewBox', f1(w), f1(h));
